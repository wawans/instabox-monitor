package crypto

import (
	"bytes"
	"encoding/hex"
	"errors"
	"os"
	"path/filepath"
	"testing"
)

func TestEncryptDecryptAndMismatch(t *testing.T) {
	hexKey := hex.EncodeToString(bytes.Repeat([]byte{0x42}, 32))
	c1, err := New(hexKey, t.TempDir())
	if err != nil {
		t.Fatalf("New(hexKey) error: %v", err)
	}
	if c1.AutoGenerated() {
		t.Errorf("AutoGenerated() = true when APP_KEY provided")
	}

	secret := "ibk_test_0123456789abcdef"
	ct1, err := c1.Encrypt(secret)
	if err != nil {
		t.Fatalf("Encrypt error: %v", err)
	}
	ct2, err := c1.Encrypt(secret)
	if err != nil {
		t.Fatalf("Encrypt second error: %v", err)
	}
	if bytes.Equal(ct1, ct2) {
		t.Fatalf("expected random nonce to yield different ciphertexts")
	}

	got, err := c1.Decrypt(ct1)
	if err != nil {
		t.Fatalf("Decrypt error: %v", err)
	}
	if got != secret {
		t.Fatalf("Decrypt = %q, want %q", got, secret)
	}

	// Wrong APP_KEY must fail with ErrDecryptFailed
	c2, err := New("another-app-key", t.TempDir())
	if err != nil {
		t.Fatalf("New(another) error: %v", err)
	}
	if _, err := c2.Decrypt(ct1); !errors.Is(err, ErrDecryptFailed) {
		t.Fatalf("expected ErrDecryptFailed, got %v", err)
	}
}

func TestAutoGeneratedMasterKeyPersistence(t *testing.T) {
	dir := t.TempDir()
	c1, err := New("", dir)
	if err != nil {
		t.Fatalf("New(auto) error: %v", err)
	}
	if !c1.AutoGenerated() {
		t.Errorf("expected AutoGenerated() = true on first boot")
	}

	info, err := os.Stat(filepath.Join(dir, ".master.key"))
	if err != nil {
		t.Fatalf("expected .master.key to exist: %v", err)
	}
	if info.Mode().Perm() != 0o600 {
		t.Errorf(".master.key perm = %o, want 0600", info.Mode().Perm())
	}

	ct, err := c1.Encrypt("ibk_persist_1234")
	if err != nil {
		t.Fatalf("Encrypt error: %v", err)
	}

	// Reload from disk with empty APP_KEY
	c2, err := New("", dir)
	if err != nil {
		t.Fatalf("New(reload) error: %v", err)
	}
	if c2.AutoGenerated() {
		t.Errorf("expected AutoGenerated() = false on reload")
	}
	got, err := c2.Decrypt(ct)
	if err != nil || got != "ibk_persist_1234" {
		t.Fatalf("reloaded Decrypt = (%q, %v), want ibk_persist_1234", got, err)
	}
}

func TestHashAPIKeyAndMask(t *testing.T) {
	c, err := New("my-app-key", t.TempDir())
	if err != nil {
		t.Fatalf("New error: %v", err)
	}
	h1 := c.HashAPIKey("ibk_abc123456789")
	h2 := c.HashAPIKey("  ibk_abc123456789  ")
	h3 := c.HashAPIKey("ibk_different999")
	if h1 == "" || h1 != h2 {
		t.Fatalf("expected deterministic trimmed HMAC hash: %q vs %q", h1, h2)
	}
	if h1 == h3 {
		t.Fatalf("different keys produced identical hash")
	}

	if got := MaskAPIKey("ibk_1234567890abcd"); got != "ibk_••••abcd" {
		t.Errorf("MaskAPIKey = %q, want ibk_••••abcd", got)
	}
	if got := MaskAPIKey("short"); got != "••••" {
		t.Errorf("MaskAPIKey(short) = %q, want ••••", got)
	}
}
