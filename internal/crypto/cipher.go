package crypto

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// ErrDecryptFailed indicates ciphertext could not be authenticated/decrypted with the active APP_KEY.
var ErrDecryptFailed = errors.New("decryption failed: APP_KEY mismatch or corrupted ciphertext")

// Cipher handles AES-256-GCM encryption and keyed HMAC hashing for API keys.
type Cipher struct {
	key       []byte
	aead      cipher.AEAD
	generated bool
}

// New initializes a Cipher from appKey (hex 64 chars, base64 32 bytes, or arbitrary passphrase).
// If appKey is empty, it loads or creates a persistent 32-byte random key at <dataDir>/.master.key (0600).
func New(appKey, dataDir string) (*Cipher, error) {
	var rawKey []byte
	var generated bool

	trimmed := strings.TrimSpace(appKey)
	if trimmed != "" {
		rawKey = deriveKey(trimmed)
	} else {
		if strings.TrimSpace(dataDir) == "" {
			dataDir = "./data"
		}
		if err := os.MkdirAll(dataDir, 0o750); err != nil {
			return nil, fmt.Errorf("create data dir for master key: %w", err)
		}
		keyPath := filepath.Join(dataDir, ".master.key")
		b, err := os.ReadFile(keyPath)
		if err == nil {
			rawKey = deriveKey(strings.TrimSpace(string(b)))
		} else if errors.Is(err, os.ErrNotExist) {
			rawKey = make([]byte, 32)
			if _, err := io.ReadFull(rand.Reader, rawKey); err != nil {
				return nil, fmt.Errorf("generate random master key: %w", err)
			}
			encoded := hex.EncodeToString(rawKey) + "\n"
			if err := os.WriteFile(keyPath, []byte(encoded), 0o600); err != nil {
				return nil, fmt.Errorf("write master key %s: %w", keyPath, err)
			}
			generated = true
		} else {
			return nil, fmt.Errorf("read master key %s: %w", keyPath, err)
		}
	}

	block, err := aes.NewCipher(rawKey)
	if err != nil {
		return nil, fmt.Errorf("init aes cipher: %w", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("init aes-gcm: %w", err)
	}

	return &Cipher{
		key:       rawKey,
		aead:      aead,
		generated: generated,
	}, nil
}

// AutoGenerated reports whether the master key was newly created on disk because APP_KEY was unset.
func (c *Cipher) AutoGenerated() bool {
	return c.generated
}

// Encrypt encrypts plaintext using AES-256-GCM with a fresh random 12-byte nonce.
func (c *Cipher) Encrypt(plaintext string) ([]byte, error) {
	nonce := make([]byte, c.aead.NonceSize())
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return nil, fmt.Errorf("generate gcm nonce: %w", err)
	}
	sealed := c.aead.Seal(nonce, nonce, []byte(plaintext), nil)
	return sealed, nil
}

// Decrypt decrypts AES-256-GCM ciphertext created by Encrypt.
func (c *Cipher) Decrypt(ciphertext []byte) (string, error) {
	ns := c.aead.NonceSize()
	if len(ciphertext) < ns {
		return "", ErrDecryptFailed
	}
	nonce, body := ciphertext[:ns], ciphertext[ns:]
	plain, err := c.aead.Open(nil, nonce, body, nil)
	if err != nil {
		return "", fmt.Errorf("%w: %v", ErrDecryptFailed, err)
	}
	return string(plain), nil
}

// HashAPIKey computes a deterministic keyed HMAC-SHA256 hex digest of an API key.
// Used for duplicate detection and seed rotation checks without storing plaintext.
func (c *Cipher) HashAPIKey(apiKey string) string {
	mac := hmac.New(sha256.New, c.key)
	mac.Write([]byte("instabox-api-key-v1:"))
	mac.Write([]byte(strings.TrimSpace(apiKey)))
	return hex.EncodeToString(mac.Sum(nil))
}

// MaskAPIKey returns a non-reversible safe preview such as "ibk_••••9f2a".
func MaskAPIKey(apiKey string) string {
	s := strings.TrimSpace(apiKey)
	if s == "" {
		return ""
	}
	if len(s) <= 8 {
		return "••••"
	}
	prefix := ""
	if idx := strings.IndexByte(s, '_'); idx > 0 && idx <= 5 {
		prefix = s[:idx+1]
	} else {
		prefix = s[:4]
	}
	suffix := s[len(s)-4:]
	return prefix + "••••" + suffix
}

func deriveKey(input string) []byte {
	if len(input) == 64 {
		if b, err := hex.DecodeString(input); err == nil && len(b) == 32 {
			return b
		}
	}
	if b, err := base64.StdEncoding.DecodeString(input); err == nil && len(b) == 32 {
		return b
	}
	if b, err := base64.RawStdEncoding.DecodeString(input); err == nil && len(b) == 32 {
		return b
	}
	sum := sha256.Sum256([]byte(input))
	return sum[:]
}
