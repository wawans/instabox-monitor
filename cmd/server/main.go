package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"
	_ "time/tzdata"

	"instabox-monitor/internal/api"
	"instabox-monitor/internal/config"
	"instabox-monitor/internal/crypto"
	"instabox-monitor/internal/logger"
	"instabox-monitor/internal/poller"
	"instabox-monitor/internal/store"
	"instabox-monitor/internal/webui"
)

var version = "dev"

func main() {
	healthcheck := flag.Bool("healthcheck", false, "run HTTP healthcheck against local server and exit 0/1")
	showVersion := flag.Bool("version", false, "print version and exit")
	flag.Parse()

	if *showVersion {
		fmt.Println(version)
		return
	}

	cfg, err := config.Load()
	if err != nil {
		fmt.Fprintf(os.Stderr, "config error: %v\n", err)
		os.Exit(1)
	}

	if *healthcheck {
		if err := runHealthcheck(cfg.Port); err != nil {
			fmt.Fprintf(os.Stderr, "healthcheck failed: %v\n", err)
			os.Exit(1)
		}
		return
	}

	log, logCloser, err := logger.New(cfg.IsDebug(), cfg.LogDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "logger init error: %v\n", err)
		os.Exit(1)
	}
	defer func() { _ = logCloser.Close() }()

	log.Info("starting InstaBox Monitor",
		"version", version,
		"port", cfg.Port,
		"appEnv", cfg.AppEnv,
		"debugFileLogging", cfg.IsDebug(),
		"authEnabled", cfg.AuthEnabled(),
		"pollIntervalSec", cfg.PollIntervalSeconds,
		"metricsPollIntervalSec", cfg.MetricsPollIntervalSeconds,
		"maxAuthFailures", cfg.AccountMaxAuthFailures,
		"seedMode", cfg.AccountsSeedMode,
	)

	ciph, err := crypto.New(cfg.AppKey, cfg.DataDir)
	if err != nil {
		log.Error("failed to initialize encryption cipher", "error", err)
		os.Exit(1)
	}
	if ciph.AutoGenerated() {
		log.Warn("APP_KEY is not set; generated random master key at DATA_DIR/.master.key — set APP_KEY explicitly in production")
	}

	st, err := store.Open(cfg.DataDir)
	if err != nil {
		log.Error("failed to open SQLite database", "dataDir", cfg.DataDir, "error", err)
		os.Exit(1)
	}
	defer func() { _ = st.Close() }()

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	seedRes, err := config.SeedAccounts(ctx, cfg, st, ciph, log)
	if err != nil {
		log.Error("account seeding failed", "error", err)
	} else if seedRes.Created+seedRes.Updated+seedRes.Skipped > 0 {
		log.Info("account seeding completed", "created", seedRes.Created, "updated", seedRes.Updated, "skipped", seedRes.Skipped)
	}

	pm := poller.NewManager(cfg, st, ciph, log)
	if err := pm.Start(ctx); err != nil {
		log.Error("failed to start background poller", "error", err)
		os.Exit(1)
	}
	defer pm.Stop()

	srvHandler := api.NewServer(cfg, st, ciph, pm, log, version, webui.Handler())
	httpSrv := &http.Server{
		Addr:              fmt.Sprintf(":%d", cfg.Port),
		Handler:           srvHandler,
		ReadHeaderTimeout: 10 * time.Second,
	}

	errCh := make(chan error, 1)
	go func() {
		log.Info("HTTP server listening", "addr", httpSrv.Addr)
		if err := httpSrv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			errCh <- err
		}
		close(errCh)
	}()

	select {
	case <-ctx.Done():
		log.Info("shutdown signal received; draining connections")
	case err := <-errCh:
		if err != nil {
			log.Error("HTTP server exited with error", "error", err)
			os.Exit(1)
		}
	}

	shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := httpSrv.Shutdown(shutdownCtx); err != nil {
		log.Error("graceful shutdown error", "error", err)
	}
	log.Info("InstaBox Monitor stopped cleanly")
}

func runHealthcheck(port int) error {
	client := &http.Client{Timeout: 4 * time.Second}
	resp, err := client.Get(fmt.Sprintf("http://127.0.0.1:%d/api/health", port))
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("unexpected status %d", resp.StatusCode)
	}
	return nil
}
